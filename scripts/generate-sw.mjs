// Generates out/sw.js: precaches every file of the static export so the app works fully offline.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const outDir = join(import.meta.dirname, "..", "out");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(outDir);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = relative(outDir, f).split(sep).join("/");
  if (rel === "sw.js" || rel.endsWith(".map") || rel === "404.html" || rel.startsWith("404/")) continue;
  hash.update(rel).update(readFileSync(f));
  urls.push("/" + rel.replace(/(^|\/)index\.html$/, "$1"));
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Auto-generated by scripts/generate-sw.mjs — do not edit.
const CACHE = "llegim-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Add in small batches so one slow file doesn't block everything.
      for (let i = 0; i < PRECACHE.length; i += 20) {
        await cache.addAll(PRECACHE.slice(i, i + 20));
      }
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("llegim-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      let path = url.pathname;
      if (req.mode === "navigate" && !path.endsWith("/") && !path.includes(".")) path += "/";
      const cached = await cache.match(path, { ignoreSearch: true });
      if (cached) return cached;
      try {
        return await fetch(req);
      } catch (err) {
        if (req.mode === "navigate") return (await cache.match("/")) ?? Response.error();
        throw err;
      }
    })(),
  );
});
`;
writeFileSync(join(outDir, "sw.js"), sw);
console.log(`sw.js generated: ${urls.length} files precached (version ${version})`);
